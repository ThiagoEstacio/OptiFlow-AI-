router = APIRouter()
logger = logging.getLogger(__name__)


class DriftCheckRequest(BaseModel):
    """Request for drift detection"""
    model_name: str
    reference_period_days: int = 30  # Training data period
    current_period_days: int = 7     # Recent data period
    target_column: Optional[str] = None
    numerical_features: Optional[List[str]] = None
    categorical_features: Optional[List[str]] = None


class DriftCheckResponse(BaseModel):
    """Response from drift detection"""
    data_drift: dict
    performance_drift: Optional[dict] = None
    should_retrain: bool
    retraining_decision: dict
    timestamp: str


